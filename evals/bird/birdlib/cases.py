"""Render per-DB `oxy test` files from BIRD questions. Never emits `evidence`."""
import json
from pathlib import Path

from . import config


def _q(s: str) -> str:
    # JSON strings are valid YAML double-quoted scalars.
    return json.dumps(s, ensure_ascii=False)


def render_test_file(db: str, rows: list[dict], disputed: set[int], runs: int = 1) -> str:
    out = [
        f"# Generated by `bird.py gen-cases`; do not edit by hand.",
        f"name: {_q('bird-' + db)}",
        f"target: {db}.agentic.yml",
        "settings:",
        f"  runs: {runs}",
        "  grader: execution",
        f"  database: {config.pg_database(db)}",
        "cases:",
    ]
    for r in sorted(rows, key=lambda r: r["question_id"]):
        if r["db_id"] != db or r["question_id"] in disputed:
            continue
        out += [
            f"  - name: {_q('bird-' + str(r['question_id']))}",
            f"    prompt: {_q(r['question'])}",
            f"    expected_sql: {_q(r['SQL'])}",
            f"    tags: [{_q(r['difficulty'])}, {_q(db)}]",
        ]
    return "\n".join(out) + "\n"


def load_rows() -> list[dict]:
    with open(config.CACHE / config.JSONL_NAME) as f:
        return [json.loads(l) for l in f if l.strip()]


def disputed_ids(entries: list) -> set[int]:
    """Entries are bare ids or `{"question_id": n, "reason": "..."}`."""
    return {e["question_id"] if isinstance(e, dict) else e for e in entries}


def gen_cases(runs: int = 1) -> None:
    root = Path(__file__).resolve().parent.parent
    disputed = disputed_ids(json.loads((root / "disputed.json").read_text()))
    rows = load_rows()
    for db in config.DBS:
        text = render_test_file(db, rows, disputed, runs)
        (root / f"{db}.test.yml").write_text(text)
        print(f"{db}.test.yml: {text.count('expected_sql:')} cases")

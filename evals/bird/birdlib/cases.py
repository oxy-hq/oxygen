"""Render per-DB `oxy dev test` files from BIRD questions. Never emits `evidence`."""
import json
from pathlib import Path

from . import config


def _q(s: str) -> str:
    # JSON strings are valid YAML double-quoted scalars.
    return json.dumps(s, ensure_ascii=False)


# Arms. `semantic` is the react runtime with `semantic_only: true`: its records say `react`.
RUNTIMES = ("fsm", "react", "semantic")

# The `runtime` an arm's records carry.
RECORDED_RUNTIME = {"fsm": "fsm", "react": "react", "semantic": "react"}


def agent_file(db: str, runtime: str = "fsm") -> str:
    return f"{db}.agentic.yml" if runtime == "fsm" else f"{db}.{runtime}.agentic.yml"


# Halves for the memory transfer pass: learn on one, test on the other.
HALVES = ("a", "b")


def test_file(db: str, runtime: str = "fsm", half: str | None = None) -> str:
    stem = db if runtime == "fsm" else f"{db}.{runtime}"
    return f"{stem}.test.yml" if half is None else f"{stem}.half-{half}.test.yml"


def pick_half(rows: list[dict], half: str | None) -> list[dict]:
    """`a` is the first half by question id (the larger one when odd), `b` the rest."""
    if half is None:
        return rows
    cut = (len(rows) + 1) // 2
    return rows[:cut] if half == "a" else rows[cut:]


def render_test_file(db: str, rows: list[dict], disputed: set[int], runs: int = 1,
                     runtime: str = "fsm", half: str | None = None) -> str:
    suite = "bird-" + db if runtime == "fsm" else f"bird-{runtime}-{db}"
    if half is not None:
        suite += f"-half-{half}"
    out = [
        f"# Generated by `bird.py gen-cases`; do not edit by hand.",
        f"name: {_q(suite)}",
        f"target: {agent_file(db, runtime)}",
        "settings:",
        f"  runs: {runs}",
        "  grader: execution",
        f"  database: {config.pg_database(db)}",
        "cases:",
    ]
    kept = [r for r in sorted(rows, key=lambda r: r["question_id"])
            if r["db_id"] == db and r["question_id"] not in disputed]
    for r in pick_half(kept, half):
        out += [
            f"  - name: {_q('bird-' + str(r['question_id']))}",
            f"    prompt: {_q(r['question'])}",
            f"    expected_sql: {_q(r['SQL'])}",
            f"    tags: [{_q(r['difficulty'])}, {_q(db)}]",
        ]
    return "\n".join(out) + "\n"


def load_rows() -> list[dict]:
    with open(config.CACHE / config.JSONL_NAME) as f:
        return [json.loads(l) for l in f if l.strip()]


def disputed_ids(entries: list) -> set[int]:
    """Entries are bare ids or `{"question_id": n, "reason": "..."}`."""
    return {e["question_id"] if isinstance(e, dict) else e for e in entries}


def gen_cases(runs: int = 1, runtime: str = "fsm", half: str | None = None) -> None:
    root = Path(__file__).resolve().parent.parent
    disputed = disputed_ids(json.loads((root / "disputed.json").read_text()))
    rows = load_rows()
    for db in config.DBS:
        text = render_test_file(db, rows, disputed, runs, runtime, half)
        name = test_file(db, runtime, half)
        (root / name).write_text(text)
        print(f"{name}: {text.count('expected_sql:')} cases")

#!/usr/bin/env node
// sync-canary-zoo: copy the shape zoo into its two consumers, with its digest.
//
// Two byte copies of fixtures/data-shapes/zoo.json, each beside the code that answers reads
// from it, because neither consumer can read the fixture at the moment it needs it:
//
// - customer-apps/examples/platform-canary/functions/: the canary is its own pnpm root, and
//   `oxyc publish` bundles only what its functions import.
// - sdk/typescript/src/testing/: `@oxy-hq/sdk/testing` is published, and an app's tests run
//   against the installed package, not this repo. The zoo is NOT published from the SDK for the
//   canary to import — that would make the SDK a data package and invert the dependency
//   (internal-docs/sdk-testing-context.md §7, answer 5) — so the SDK carries its own copy.
//
// Each copy's zoo table is named from the file's SHA-256, which a JSON import cannot recover, so
// the digest travels beside the copy. Each consumer's own `shape-zoo-sync.test.ts` fails until
// this has been run after any zoo change, and the `canary-zoo` CI job restates both checks in
// shell.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "fixtures", "data-shapes", "zoo.json");

/** Where the copies land; the digest module beside each is `shape-zoo-sha256.ts`. */
const destinations = [
  join(root, "customer-apps", "examples", "platform-canary", "functions"),
  join(root, "sdk", "typescript", "src", "testing")
];

const bytes = readFileSync(source);
const sha256 = createHash("sha256").update(bytes).digest("hex");
for (const dir of destinations) {
  writeFileSync(join(dir, "shape-zoo.json"), bytes);
  writeFileSync(
    join(dir, "shape-zoo-sha256.ts"),
    "// Generated by scripts/data-shapes/sync-canary-zoo.mjs from fixtures/data-shapes/zoo.json.\n" +
      `export const ZOO_SHA256 = "${sha256}";\n`
  );
}
console.log(`shape zoo ${sha256.slice(0, 8)} synced to ${destinations.length} destinations`);

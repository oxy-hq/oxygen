#!/usr/bin/env node
// sync-canary-zoo: copy the shape zoo into the platform canary, with its digest.
//
// The canary is its own pnpm root, and `oxyc publish` bundles only what its functions import,
// so it carries a byte copy of fixtures/data-shapes/zoo.json. Its zoo table is named from the
// file's SHA-256, which a JSON import cannot recover, so the digest travels beside the copy.
// functions/shape-zoo-sync.test.ts fails until this has been run after any zoo change.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "fixtures", "data-shapes", "zoo.json");
const functions = join(root, "customer-apps", "examples", "platform-canary", "functions");

const bytes = readFileSync(source);
const sha256 = createHash("sha256").update(bytes).digest("hex");
writeFileSync(join(functions, "shape-zoo.json"), bytes);
writeFileSync(
  join(functions, "shape-zoo-sha256.ts"),
  "// Generated by scripts/data-shapes/sync-canary-zoo.mjs from fixtures/data-shapes/zoo.json.\n" +
    `export const ZOO_SHA256 = "${sha256}";\n`
);
console.log(`shape zoo ${sha256.slice(0, 8)} synced to platform-canary`);

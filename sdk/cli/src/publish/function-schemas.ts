/**
 * A function's `inputSchema` / `outputSchema`, generated from its TypeScript
 * types at `oxyc publish` and written into the BUNDLE's `oxy-app.json` — the
 * copy the platform reads — never into the source manifest.
 *
 * Where a function's types are found, first match wins:
 *
 * - input: a type named `Input` the entry declares or imports from a relative
 *   file; else the type the default-export handler casts its body to,
 *   `JSON.parse(req.body …) as T`;
 * - output: a type named `Output`, likewise; else the handler's declared
 *   return type, `Promise<T>` unwrapped — nothing when it returns a `Response`.
 *
 * A schema the manifest already holds is the author's and wins; `null` there
 * means "none" and is kept too. Only a schema this step wrote before (its
 * `$comment` says so — a `--dir` bundle published twice) is regenerated.
 *
 * Generation never fails a publish. A type outside what
 * `schema/ts-json-schema.ts` understands, or a result the subset check or the
 * size cap refuses, is a warning naming the function and the fix — write the
 * schema by hand — and that function ships without one.
 */

import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import {
  checkFunctionSchema,
  FUNCTION_SCHEMA_MAX_BYTES,
  serializedSchemaBytes
} from "@oxy-hq/sdk/manifest";
import {
  type JsonSchema,
  matchBracket,
  parseTypeAt,
  parseTypeSpan,
  type ReadSource,
  schemaForDeclaration,
  schemaForType,
  type TypeModule,
  type TypeNode,
  TypeProgram,
  UnsupportedType
} from "../schema/ts-json-schema.js";
import { functionEntry, type PublishManifest } from "./manifest.js";

/** Marks a schema this step wrote, so a later run may replace it. */
export const GENERATED_COMMENT_PREFIX = "Generated by oxyc publish from ";

/** One generated schema and what it came from, for the report. */
export interface Generated {
  schema: JsonSchema;
  /** `Input`, or `the handler's return type`. */
  from: string;
}

/** What one function's source yields. */
export interface FunctionTypes {
  input?: Generated;
  output?: Generated;
  /** A type was found but could not be converted: one sentence each. */
  problems: Array<{ key: "inputSchema" | "outputSchema"; from: string; message: string }>;
}

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/** Whether `offset` sits outside every `{…}` of the masked text. */
function topLevel(masked: string, offset: number): boolean {
  let depth = 0;
  for (let i = 0; i < offset; i++) {
    if (masked[i] === "{") depth++;
    else if (masked[i] === "}") depth = Math.max(0, depth - 1);
  }
  return depth === 0;
}

/** The default-export handler: its first parameter, return type and body. */
interface Handler {
  param?: string;
  /** Offset of the return type annotation, after `:`. */
  returnAt?: number;
  /** `[open, close)` of the body braces, when it has a block body. */
  body?: [number, number];
}

function findHandler(module: TypeModule): Handler | undefined {
  const { masked } = module;
  const exp = /(^|[;\s}])export\s+default\s+/g;
  let cursor: number | undefined;
  for (let m = exp.exec(masked); m !== null; m = exp.exec(masked)) {
    if (topLevel(masked, m.index)) {
      cursor = m.index + m[0].length;
      break;
    }
  }
  if (cursor === undefined) return undefined;

  const rest = masked.slice(cursor);
  // `export default handler;` — find the function declaration it names.
  const named = /^([A-Za-z_$][\w$]*)\s*;?\s*(?:\n|$)/.exec(rest);
  if (named && named[1] !== "async" && named[1] !== "function") {
    const decl = new RegExp(`(^|[;\\s}])(?:async\\s+)?function\\s+${named[1]}\\s*\\(`, "g");
    let found: number | undefined;
    for (let m = decl.exec(masked); m !== null; m = decl.exec(masked)) {
      if (topLevel(masked, m.index)) {
        found = m.index + m[0].length - 1;
        break;
      }
    }
    if (found === undefined) return undefined;
    cursor = found;
  } else {
    const head = /^(?:async\s+)?(?:function\s*\*?\s*(?:[A-Za-z_$][\w$]*)?\s*)?/.exec(rest);
    cursor += head?.[0].length ?? 0;
  }
  if (masked[cursor] !== "(") return undefined;

  const paramsEnd = matchBracket(masked, cursor);
  if (paramsEnd === undefined) return undefined;
  const param = /^\(\s*([A-Za-z_$][\w$]*)/.exec(masked.slice(cursor, paramsEnd))?.[1];
  const handler: Handler = { param };

  let after = paramsEnd;
  const colon = /^\s*:/.exec(masked.slice(after));
  if (colon) {
    handler.returnAt = after + colon[0].length;
    try {
      after = parseTypeSpan(module, handler.returnAt).end;
    } catch {
      // An annotation outside the subset: the output attempt reports it.
      return handler;
    }
  }
  const open = /^\s*(?:=>\s*)?\{/.exec(masked.slice(after));
  if (open) {
    const start = after + open[0].length - 1;
    const end = matchBracket(masked, start);
    if (end !== undefined) handler.body = [start, end];
  }
  return handler;
}

/** `JSON.parse(<param>.body …) as T` in the handler body: the offset of `T`. */
function bodyCast(module: TypeModule, handler: Handler): number | undefined {
  if (!handler.param || !handler.body) return undefined;
  const { masked } = module;
  const [start, end] = handler.body;
  const call = /\bJSON\s*\.\s*parse\s*\(/g;
  call.lastIndex = start;
  // `$` is legal in an identifier and special in a pattern.
  const name = handler.param.replace(/\$/g, "\\$");
  const reads = new RegExp(`\\b${name}\\s*\\.\\s*body\\b`);
  for (let m = call.exec(masked); m !== null && m.index < end; m = call.exec(masked)) {
    const open = m.index + m[0].length - 1;
    const close = matchBracket(masked, open);
    if (close === undefined) continue;
    if (!reads.test(masked.slice(open, close))) continue;
    const cast = /^\s*as\s+/.exec(masked.slice(close));
    if (cast) return close + cast[0].length;
  }
  return undefined;
}

/** A return type that is not data: nothing to describe. */
function isNotData(node: TypeNode): boolean {
  if (node.k === "ref") return node.name === "Response";
  if (node.k === "keyword")
    return ["void", "undefined", "unknown", "any", "never"].includes(node.name);
  if (node.k === "union") return node.members.some(isNotData);
  return false;
}

/**
 * The input and output schemas one function's source yields. `root` is what
 * a problem's file is shown relative to (the app directory).
 */
export function functionTypesFromSource(
  entryPath: string,
  read: ReadSource,
  root: string = dirname(entryPath)
): FunctionTypes {
  const program = new TypeProgram(read);
  const result: FunctionTypes = { problems: [] };
  const module = program.module(entryPath);
  if (!module) return result;

  /** `make` answers `undefined` for a type that is not data: nothing to say. */
  const attempt = (
    key: "inputSchema" | "outputSchema",
    from: string,
    make: () => JsonSchema | undefined
  ): Generated | undefined => {
    try {
      const schema = make();
      return schema && { schema, from };
    } catch (cause) {
      if (!(cause instanceof UnsupportedType)) throw cause;
      const where = `${relative(root, cause.file).split(sep).join("/")}:${cause.line}`;
      result.problems.push({ key, from, message: `${cause.message} (${where})` });
      return undefined;
    }
  };

  const handler = findHandler(module);

  if (program.resolve(module, "Input")) {
    result.input = attempt("inputSchema", "`Input`", () =>
      schemaForDeclaration(program, module, "Input")
    );
  } else if (handler) {
    const at = bodyCast(module, handler);
    if (at !== undefined) {
      const from = `the handler's \`JSON.parse(${handler.param}.body) as …\``;
      result.input = attempt("inputSchema", from, () =>
        schemaForType(program, module, parseTypeAt(module, at))
      );
    }
  }

  if (program.resolve(module, "Output")) {
    result.output = attempt("outputSchema", "`Output`", () =>
      schemaForDeclaration(program, module, "Output")
    );
  } else if (handler?.returnAt !== undefined) {
    const returnAt = handler.returnAt;
    result.output = attempt("outputSchema", "the handler's return type", () => {
      let node = parseTypeAt(module, returnAt);
      if (node.k === "ref" && node.name === "Promise" && node.args.length === 1) {
        node = node.args[0] as TypeNode;
      }
      return isNotData(node) ? undefined : schemaForType(program, module, node);
    });
  }
  return result;
}

/** A reader confined to `appDir`: a type import that leaves it is not followed. */
export function appSourceReader(appDir: string): ReadSource {
  const root = resolve(appDir);
  return (path) => {
    const abs = resolve(path);
    if (abs !== root && !abs.startsWith(root + sep)) return undefined;
    if (abs.split(sep).includes("node_modules")) return undefined;
    try {
      if (!statSync(abs).isFile()) return undefined;
      return readFileSync(abs, "utf8");
    } catch {
      return undefined;
    }
  };
}

/** What `embedFunctionSchemas` did, for the publish log. */
export interface EmbedReport {
  /** `quote: inputSchema from \`Input\`` — one per schema written. */
  generated: string[];
  /** One sentence per schema that could not be generated. */
  warnings: string[];
}

/** Whether `oxyc publish` may (re)write the schema at `key` of `spec`. */
function writable(spec: Record<string, unknown>, key: string): boolean {
  const current = spec[key];
  if (current === undefined) return true;
  return (
    isRecord(current) &&
    typeof current.$comment === "string" &&
    current.$comment.startsWith(GENERATED_COMMENT_PREFIX)
  );
}

/**
 * The object written into the manifest: the generated schema with the
 * `$comment` that marks it ours, `$schema` kept first.
 */
export function shippedSchema(generated: Generated, entry: string): JsonSchema {
  const { $schema, ...rest } = generated.schema;
  return {
    $schema,
    $comment: `${GENERATED_COMMENT_PREFIX}${entry} (${generated.from.replace(/`/g, "")})`,
    ...rest
  };
}

/**
 * Why `shipped` cannot go into the manifest, or `undefined`. Checked on the
 * object as it will ship — `$comment` included — since that is what publish
 * measures and walks: a schema that fits only without its comment would pass
 * here and be refused there.
 */
function admissible(shipped: JsonSchema): string | undefined {
  const size = serializedSchemaBytes(shipped);
  if (size > FUNCTION_SCHEMA_MAX_BYTES) {
    return `the schema is ${size} bytes, over the ${FUNCTION_SCHEMA_MAX_BYTES}-byte cap`;
  }
  const problem = checkFunctionSchema(shipped);
  if (problem) return `${[...problem.path].join(".") || "the schema"} ${problem.message}`;
  return undefined;
}

/**
 * Generate the schemas the bundle's `oxy-app.json` lacks and write them into
 * it. A bundle without one (a build that does not copy the manifest) is left
 * alone: the platform registers no functions from it either.
 */
export function embedFunctionSchemas(
  appDir: string,
  bundleDir: string,
  manifest: PublishManifest | undefined,
  read: ReadSource = appSourceReader(appDir)
): EmbedReport {
  const report: EmbedReport = { generated: [], warnings: [] };
  const path = join(bundleDir, "oxy-app.json");
  if (!existsSync(path)) return report;
  let bundled: unknown;
  try {
    bundled = JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return report;
  }
  if (!isRecord(bundled) || !isRecord(bundled.functions)) return report;

  let changed = false;
  for (const [name, spec] of Object.entries(bundled.functions)) {
    if (!isRecord(spec)) continue;
    const wantInput = writable(spec, "inputSchema");
    const wantOutput = writable(spec, "outputSchema");
    if (!wantInput && !wantOutput) continue;

    const entry = functionEntry(manifest ?? (bundled as Record<string, unknown>), name);
    const types = functionTypesFromSource(resolve(appDir, entry), read, appDir);
    const pairs: Array<["inputSchema" | "outputSchema", boolean, Generated | undefined]> = [
      ["inputSchema", wantInput, types.input],
      ["outputSchema", wantOutput, types.output]
    ];
    for (const [key, wanted, generated] of pairs) {
      if (!wanted) continue;
      const stale = spec[key] !== undefined;
      const problem = types.problems.find((p) => p.key === key);
      if (problem) {
        report.warnings.push(
          `function ${JSON.stringify(name)}: no ${key} from ${problem.from} — ${problem.message}. ` +
            `Write functions.${name}.${key} in oxy-app.json by hand, or simplify the type.`
        );
      }
      if (!generated) {
        if (stale) {
          delete spec[key];
          changed = true;
        }
        continue;
      }
      const shipped = shippedSchema(generated, entry);
      const refused = admissible(shipped);
      if (refused) {
        report.warnings.push(
          `function ${JSON.stringify(name)}: the ${key} generated from ${generated.from} is not ` +
            `shipped — ${refused}. Write functions.${name}.${key} in oxy-app.json by hand.`
        );
        if (stale) {
          delete spec[key];
          changed = true;
        }
        continue;
      }
      spec[key] = shipped;
      changed = true;
      report.generated.push(`${name}: ${key} from ${generated.from}`);
    }
  }
  if (changed) writeFileSync(path, `${JSON.stringify(bundled, null, 2)}\n`);
  return report;
}

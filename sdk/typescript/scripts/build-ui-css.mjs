// Builds the desk UI's stylesheets into dist/ (run by tsdown's onSuccess and by the dev watcher):
//
//   dist/ui.css        src/ui/base.css, then each group's <group>.css in GROUPS order, inside one
//                      `@layer oxy-ui { … }`, after the layer-order statement tailwind.css also
//                      states (`theme, base, oxy-ui, components, utilities`)
//   dist/tailwind.css  src/ui/tailwind.css, copied
//
//   node scripts/build-ui-css.mjs            write both
//   node scripts/build-ui-css.mjs --stdout   print ui.css and write nothing
//
// Plain Node, no dependencies, deterministic. A group CSS file holds rules only: an @import,
// @layer or @charset inside one would break out of the layer, so it fails the build (and
// src/ui/uiCss.test.ts).

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The groups, in the order their CSS follows base.css. A later group wins a tie. */
export const GROUPS = [
  "focus",
  "actions",
  "navigation",
  "figures",
  "tables",
  "charts",
  "containers",
  "forms",
  "feedback",
  "patterns"
];

export const LAYER_ORDER = "@layer theme, base, oxy-ui, components, utilities;";

/** The source files, base first, as paths relative to src/ui. */
export function uiCssSources() {
  return ["base.css", ...GROUPS.map((g) => `${g}/${g}.css`)];
}

/** dist/ui.css as a string, from the package at `root`. */
export function buildUiCss(root = PKG) {
  const parts = [];
  for (const rel of uiCssSources()) {
    const file = join(root, "src", "ui", rel);
    if (!existsSync(file)) throw new Error(`build-ui-css: ${rel} is missing`);
    const css = readFileSync(file, "utf8");
    const bare = css.replace(/\/\*[\s\S]*?\*\//g, "");
    const bad = /@(import|layer|charset)\b/.exec(bare);
    if (bad) throw new Error(`build-ui-css: ${rel} has @${bad[1]}; a group file holds rules only`);
    parts.push(`/* ---- src/ui/${rel} ---- */\n${css.trim()}\n`);
  }
  return [
    "/* @oxy-hq/sdk/ui.css: every .oxy-ui-* rule. Generated by scripts/build-ui-css.mjs from",
    " * src/ui/base.css and each group's CSS; do not edit. Import after theme.css (and shell.css). */",
    LAYER_ORDER,
    "",
    "@layer oxy-ui {",
    parts.join("\n"),
    "}",
    ""
  ].join("\n");
}

function main(argv) {
  const css = buildUiCss();
  if (argv.includes("--stdout")) {
    process.stdout.write(css);
    return 0;
  }
  const dist = join(PKG, "dist");
  mkdirSync(dist, { recursive: true });
  writeFileSync(join(dist, "ui.css"), css);
  copyFileSync(join(PKG, "src", "ui", "tailwind.css"), join(dist, "tailwind.css"));
  console.log("build-ui-css: dist/ui.css, dist/tailwind.css");
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(err.message);
    process.exitCode = 1;
  }
}

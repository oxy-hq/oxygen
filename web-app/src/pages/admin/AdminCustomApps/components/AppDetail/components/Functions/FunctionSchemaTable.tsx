import type { AppFunctionSummary } from "@/types/apps";
import { type JsonSchema, schemaFields } from "./functionSchema";

/**
 * A function's declared input and output schemas, each as a compact field
 * table. Nothing when it declares neither — the Run now hint says how to.
 */
export const FunctionSchemas = ({ fn }: { fn: AppFunctionSummary }) => {
  if (!fn.input_schema && !fn.output_schema) return null;
  return (
    <div className='flex flex-col gap-2' data-testid='admin-app-function-schemas'>
      {fn.input_schema && <FunctionSchemaTable kind='input' schema={fn.input_schema} />}
      {fn.output_schema && <FunctionSchemaTable kind='output' schema={fn.output_schema} />}
    </div>
  );
};

const GENERATED = "Generated by oxyc publish from ";

/** One schema: field, type, required, description. */
export const FunctionSchemaTable = ({
  kind,
  schema
}: {
  kind: "input" | "output";
  schema: JsonSchema;
}) => {
  const fields = schemaFields(schema);
  const generated =
    typeof schema.$comment === "string" && schema.$comment.startsWith(GENERATED)
      ? schema.$comment.slice(GENERATED.length)
      : undefined;
  return (
    <div className='flex flex-col gap-1' data-testid={`admin-app-function-schema-${kind}`}>
      <div className='flex flex-wrap items-baseline gap-x-2'>
        <h4 className='font-medium text-muted-foreground text-xs uppercase tracking-wide'>
          {kind === "input" ? "Input schema" : "Output schema"}
        </h4>
        {generated && (
          <span className='text-muted-foreground text-xs'>from the types in {generated}</span>
        )}
      </div>
      <div className='overflow-x-auto'>
        <table className='w-full text-xs'>
          <thead>
            <tr className='text-left text-muted-foreground'>
              <th className='py-0.5 pr-3 font-medium'>Field</th>
              <th className='py-0.5 pr-3 font-medium'>Type</th>
              <th className='py-0.5 pr-3 font-medium'>Required</th>
              <th className='py-0.5 font-medium'>Description</th>
            </tr>
          </thead>
          <tbody>
            {fields.map((field) => (
              <tr
                key={field.name}
                className='border-border/60 border-t align-top'
                data-testid='admin-app-function-schema-field'
              >
                <td className='whitespace-nowrap py-0.5 pr-3 font-mono'>{field.name}</td>
                <td className='py-0.5 pr-3 font-mono text-muted-foreground'>{field.type}</td>
                <td className='py-0.5 pr-3'>
                  {field.required ? "yes" : <span className='text-muted-foreground'>no</span>}
                </td>
                <td className='py-0.5 text-muted-foreground'>{field.description ?? ""}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
};
